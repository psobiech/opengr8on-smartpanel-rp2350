#!/usr/bin/env python3
"""Rasterize Noto Sans (SIL OFL 1.1) into 4-bit anti-aliased glyph tables for src/font_aa.h.

    python3 tools/gen_font.py > src/font_aa.h

Glyphs: ASCII 0x20..0x7E, plus '\\x7f' = degree sign. Needs Pillow and the Noto Sans TTFs.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONTS = [  # (C name, ttf, pixel size)
    ("font_label", "/usr/share/fonts/noto/NotoSans-SemiBold.ttf", 26),
    ("font_small", "/usr/share/fonts/noto/NotoSans-Medium.ttf", 15),
]
CHARS = [chr(c) for c in range(0x20, 0x7F)] + ["°"]


def emit(name, path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    glyphs, data = [], []
    for ch in CHARS:
        x0, y0, x1, y1 = font.getbbox(ch)
        adv = round(font.getlength(ch))
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(data)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255)
            px = list(im.tobytes())
            nib = [(v + 8) // 17 for v in px]  # 0..255 -> 0..15
            if len(nib) % 2:
                nib.append(0)
            data += [nib[i] << 4 | nib[i + 1] for i in range(0, len(nib), 2)]
        glyphs.append((w, h, x0, y0, adv, off))
    print(f"// {name}: {path.rsplit('/', 1)[-1]} {size}px, generated by tools/gen_font.py")
    print(f"static const uint8_t {name}_data[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        print("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    print("};")
    print(f"static const aa_glyph_t {name}_glyphs[{len(glyphs)}] = {{")
    for g in glyphs:
        print("    {%d, %d, %d, %d, %d, %d}," % g)
    print("};")
    print(f"static const aa_font_t {name} = {{{height}, {ascent}, {name}_glyphs, {name}_data}};\n")


print("// Anti-aliased bitmap fonts (4 bpp). Noto Sans, Copyright Google LLC, SIL Open Font License 1.1.")
print("#pragma once\n#include <stdint.h>\n")
print("typedef struct {\n    uint8_t w, h;\n    int8_t x, y; // bitmap offset from the pen position (y from the top of the line)\n"
      "    uint8_t adv;\n    uint32_t off; // into data, 2 pixels per byte, high nibble first\n} aa_glyph_t;\n")
print("typedef struct {\n    uint8_t height, ascent;\n    const aa_glyph_t *glyphs; // 0x20..0x7e, 0x7f = degree sign\n"
      "    const uint8_t *data;\n} aa_font_t;\n")
for f in FONTS:
    emit(*f)
