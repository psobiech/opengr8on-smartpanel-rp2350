#!/usr/bin/env python3
"""Rasterize Noto Sans (SIL OFL 1.1) into 4-bit anti-aliased glyph tables for src/font_aa.h.

    python3 tools/gen_font.py > src/font_aa.h

Glyphs: ASCII 0x20..0x7E, plus '\\x7f' = degree sign. Needs Pillow and the Noto Sans TTFs.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONTS = [  # (C name, ttf, pixel size)
    ("font_label", "/usr/share/fonts/noto/NotoSans-SemiBold.ttf", 26),
    ("font_small", "/usr/share/fonts/noto/NotoSans-Medium.ttf", 15),
]
CHARS = [chr(code) for code in range(0x20, 0x7F)] + ["°"]


def main():
    print("// Anti-aliased bitmap fonts (4 bpp). Noto Sans, Copyright Google LLC, SIL Open Font License 1.1.")
    print("#pragma once\n#include <stdint.h>\n")
    print("typedef struct {\n    uint8_t width, height;\n"
          "    int8_t offset_x, offset_y; // bitmap offset from the pen position (y from the top of the line)\n"
          "    uint8_t advance;\n    uint32_t data_offset; // into data, 2 pixels per byte, high nibble first\n"
          "} aa_glyph_t;\n")
    print("typedef struct {\n    uint8_t height, ascent;\n    const aa_glyph_t *glyphs; // 0x20..0x7e, 0x7f = degree sign\n"
          "    const uint8_t *data;\n} aa_font_t;\n")
    for font_spec in FONTS:
        emit(*font_spec)


def emit(name, path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    glyphs, data = [], []
    for character in CHARS:
        left, top, right, bottom = font.getbbox(character)
        advance = round(font.getlength(character))
        glyph_width, glyph_height = max(0, right - left), max(0, bottom - top)
        data_offset = len(data)
        if glyph_width and glyph_height:
            image = Image.new("L", (glyph_width, glyph_height), 0)
            ImageDraw.Draw(image).text((-left, -top), character, font=font, fill=255)
            pixels = list(image.tobytes())
            nibbles = [(value + 8) // 17 for value in pixels]  # 0..255 -> 0..15
            if len(nibbles) % 2:
                nibbles.append(0)
            data += [nibbles[i] << 4 | nibbles[i + 1] for i in range(0, len(nibbles), 2)]
        glyphs.append((glyph_width, glyph_height, left, top, advance, data_offset))
    print(f"// {name}: {path.rsplit('/', 1)[-1]} {size}px, generated by tools/gen_font.py")
    print(f"static const uint8_t {name}_data[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        print("    " + ", ".join(f"0x{byte:02x}" for byte in data[i:i + 24]) + ",")
    print("};")
    print(f"static const aa_glyph_t {name}_glyphs[{len(glyphs)}] = {{")
    for glyph in glyphs:
        print("    {%d, %d, %d, %d, %d, %d}," % glyph)
    print("};")
    print(f"static const aa_font_t {name} = {{{height}, {ascent}, {name}_glyphs, {name}_data}};\n")


if __name__ == "__main__":
    main()
